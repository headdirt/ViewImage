// Builds dist/viewimage.user.js from the extension's content script, so the
// userscript and the extension share one implementation.
//
// The content script only touches a small slice of the extension API
// (storage.sync.get, i18n.getMessage, runtime.getURL); the userscript provides
// a local `chrome` object implementing just that slice, with options coming
// from an editable USER_OPTIONS block instead of the options page.

import fs from 'node:fs';
import path from 'node:path';

const rootDir = path.resolve(import.meta.dirname, '..');
const read = file => fs.readFileSync(path.join(rootDir, file), 'utf8');
const readJSON = file => JSON.parse(read(file));

const GIST_RAW_URL = 'https://gist.github.com/headdirt/1af7759b4e3faf544a802e5300428a80/raw/viewimage.user.js';
const outputPath = path.join(rootDir, 'dist', 'viewimage.user.js');

const { version } = readJSON('package.json');
const googleTlds = readJSON('scripts/google-tlds.json');
const english = readJSON('_locales/en/messages.json');

// Only the strings the content script uses.
const MESSAGE_KEYS = ['viewImage', 'searchImage'];
const messages = {};
for (const locale of fs.readdirSync(path.join(rootDir, '_locales')).sort()) {
    const localeMessages = readJSON(`_locales/${locale}/messages.json`);
    messages[locale] = Object.fromEntries(
        MESSAGE_KEYS.filter(key => localeMessages[key]).map(key => [key, localeMessages[key].message])
    );
}

const dataURI = (file, type) => `data:${type};base64,${fs.readFileSync(path.join(rootDir, file)).toString('base64')}`;
const assets = { 'img/lens.svg': dataURI('img/lens.svg', 'image/svg+xml') };

// Everything the extension lets users configure, except the context menu,
// which a userscript can't provide.
const userOptions = { ...evaluateDefaultOptions() };
delete userOptions['context-menu-search-by-image'];

function evaluateDefaultOptions() {
    const source = read('js/default-options.js');
    return new Function(`${source}; return VIEW_IMAGE_DEFAULT_OPTIONS;`)();
}

const header = [
    '// ==UserScript==',
    '// @name            View Image',
    // Unchanged from the original userscript so existing installs keep updating.
    '// @namespace       https://github.com/bijij/ViewImage',
    `// @version         ${version}`,
    `// @description     ${english.appDesc.message}`,
    '// @author          Joshua B',
    `// @icon            ${dataURI('icon/48.png', 'image/png')}`,
    '// @run-at          document-end',
    '// @grant           none',
    ...googleTlds.flatMap(tld => [
        `// @match           *://*.${tld}/search*`,
        `// @match           *://*.${tld}/imgres*`,
    ]),
    `// @updateURL       ${GIST_RAW_URL}`,
    `// @downloadURL     ${GIST_RAW_URL}`,
    '// ==/UserScript==',
].join('\n');

// Sources are concatenated unindented: re-indenting could alter multi-line
// template literals.
const section = (file, source = read(file)) => `// --- ${file} ${'-'.repeat(Math.max(0, 70 - file.length))}\n\n${source.trim()}`;

const shim = `
// Edit to customise. Changes are lost when the script updates.
const USER_OPTIONS = ${JSON.stringify(userOptions, null, 4)};

// Generated from the extension's _locales and img/ directories.
const MESSAGES = ${JSON.stringify(messages)};
const ASSETS = ${JSON.stringify(assets)};

function getMessage(key) {
    const languages = [document.documentElement.lang, ...navigator.languages];
    for (const language of languages) {
        if (!language) continue;
        const [lang, region] = language.split(/[-_]/);
        const candidates = region ? [\`\${lang}_\${region.toUpperCase()}\`, lang] : [lang];
        for (const locale of candidates) {
            if (MESSAGES[locale]?.[key]) return MESSAGES[locale][key];
        }
    }
    return MESSAGES.en[key] || '';
}

// The subset of the extension API used by the content script.
const chrome = {
    i18n: { getMessage },
    runtime: { getURL: pathname => ASSETS[pathname] },
    storage: { sync: { get: (_keys, callback) => callback({ options: USER_OPTIONS }) } },
};

const style = document.createElement('style');
style.textContent = ${JSON.stringify(read('css/content-script.css'))};
(document.head || document.documentElement).appendChild(style);
`;

const body = [
    section('userscript shim (scripts/build-userscript.mjs)', shim),
    section('js/default-options.js'),
    section('js/extension-api.js'),
    section('js/i18n.js'),
    section('js/content-script.js'),
].join('\n\n');

const userscript = `${header}

// Generated by scripts/build-userscript.mjs from https://github.com/headdirt/ViewImage.
// Do not edit by hand; changes belong in the extension source.

(function () {
'use strict';

${body}
})();
`;

fs.mkdirSync(path.dirname(outputPath), { recursive: true });
fs.writeFileSync(outputPath, userscript);
console.log(`Wrote ${path.relative(rootDir, outputPath)} (${version})`);
